/**
 * Social-emotional scenarios for the Friends Village (כישורי חיים / SEL).
 * Design rules from the research (Durlak 2011 SAFE; Narvaez; Mares & Acosta 2008):
 * - the target skill is named explicitly, the child is never asked to infer a moral;
 * - choices have consequences, there is no "wrong answer" sound and no score;
 * - every scenario ends with reflection and one question to take home.
 * Text uses {m|f} markers for addressing the child (see core/rng.g).
 */
export interface Choice {
  text: string;
  outcome: string;
  feeling: string;
  /** Present on the constructive choice: the named skill the child practiced. */
  skill?: string;
}

export interface Scenario {
  id: string;
  who: string;
  title: string;
  situation: string;
  choices: [Choice, Choice, Choice];
  home: string;
}

